# -- they compile, and an embedded manifest loads through the C ABI --------------------------------------------------------------------------


def compile_syntax(sources, include_dirs):
    args = [CXX, "-std=c++17", "-Wall", "-Wextra", "-Werror", "-fsyntax-only", "-I", str(INCLUDE), *[f"-I{d}" for d in include_dirs]]
    for source in sources:
        done = subprocess.run([*args, str(source)], capture_output=True, text=True, timeout=600)
        assert done.returncode == 0, f"{source}:\n{done.stderr[-4000:]}"


