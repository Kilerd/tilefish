def test_one_class_per_stem_typed_from_the_manifest(fake_manifest):
    source = cpp.render(fake_manifest)
    assert f'inline constexpr const char* MANIFEST_DIGEST = "{fake_manifest.digest}";' in source
    assert source.startswith("// @generated by tilefish.hosts.cpp.") and '#include "tilefish.hpp"\n' in source
    assert "namespace tilefish_launchers {" in source and source.rstrip().endswith("_HPP")
    for cls in ("Scale", "RowopS32", "RowopS64"):
        assert f"class {cls} {{" in source
    body = class_body(source, "RowopS32")
    assert 'static constexpr const char* STEM = "rowop.S32";' in body
    assert 'static constexpr std::array<tilefish_bucket, 1> BUCKETS = {{{"S", 32}}};' in body
    assert 'static constexpr std::array<const char*, 2> X_SHAPE = {{"M", "S"}};' in body
    assert "manifest.require_digest(MANIFEST_DIGEST);" in body
    assert "return RowopS32(manifest.kernel(ctx, STEM, tilefish::detail::Span<tilefish_bucket>(BUCKETS.data(), BUCKETS.size())));" in body
    params = launch_params(body)
    assert "CUstream stream" in params and "const tilefish::TensorRef<tilefish::F32>& x" in params and "const tilefish::TensorMut<tilefish::F32>& y" in params
    assert "kernel_.launch(stream, {x, y});" in body and "kernel_.check({x, y});" in body
    assert "explicit RowopS32(tilefish::Kernel loaded) : kernel_(std::move(loaded)) {}" in body
    # no dimension, scalar or grid is a parameter: the tensors are all a launch takes
    assert "n_elem" not in launch_params(class_body(source, "Scale"))
    assert "Constraints: `S` is exactly 32 (a bucket of [32, 64]; there is no padding, and the other buckets are other classes)." in source


