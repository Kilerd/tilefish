def test_the_output_is_deterministic(fake_manifest, tmp_path):
    first = cpp.render(fake_manifest, ops=[scale, rowop])
    assert cpp.render(fake_manifest, ops=[rowop, scale]) == first
    doc = json.loads(fake_manifest.path.read_text())
    doc["kernels"].reverse()
    other = tmp_path / "reordered"
    shutil.copytree(fake_manifest.directory, other)
    (other / "manifest.json").write_text(json.dumps(doc, indent=2) + "\n")
    assert cpp.render(pinned(Manifest.load(other)), ops=[scale, rowop]) == first
    a, b = tmp_path / "a.hpp", tmp_path / "b.hpp"
    cpp.emit(fake_manifest, a, ops=[scale, rowop])
    cpp.emit(fake_manifest, b, ops=[scale, rowop])
    assert a.read_bytes() == b.read_bytes() == first.encode("utf-8")


