def test_names_that_clash_with_cpp_or_the_generated_code_are_renamed(fake_manifest, tmp_path):
    from test_rust_host import edited, param

    for name, renamed in [("class", "class_"), ("stream", "stream_"), ("tilefish", "tilefish_"), ("kernel_", "kernel_arg"), ("errno", "errno_"), ("x", "x")]:
        assert cpp._cpp_ident(name, "t") == renamed
    for reserved in ("_X", "a__b", "__x", "_"):
        with pytest.raises(TilefishManifestError, match="C\\+\\+ reserves"):
            cpp._cpp_ident(reserved, "t")
    assert cpp._class_name("M") == "MOp" and cpp._class_name("STEM") == "STEMOp" and cpp._class_name("Scale") == "Scale"

    def clash(entry, directory):
        entry["stem"] = entry["op"] = "m"
        param(entry, "x").update(name="stream")
        param(entry, "y").update(name="class")
        for pre in entry["preconditions"]:
            pre["arg"] = {"x": "stream", "y": "class"}.get(pre.get("arg"), pre.get("arg"))

    manifest = edited(fake_manifest, tmp_path, clash)
    source = cpp.render(manifest, pin=manifest.digest)
    body = class_body(source, "MOp")
    assert "const tilefish::TensorRef<tilefish::Bf16>& stream_" in body and "const tilefish::TensorMut<tilefish::Bf16>& class_" in body
    assert "STREAM_SHAPE" in body and "CLASS_SHAPE" in body and "kernel_.launch(stream, {stream_, class_});" in body


