@needs_cxx
def test_the_runners_and_launchers_of_fused_plans_compile(tmp_path):
    """A graph whose body computes (``fusion_graphs.CASES``, fused, and its unfused twin with a region per op): the runner of its plan and the
    launchers of its manifest, whose kernels are the regions tilefish generates (``fused_<hash>``, one class each, named by the stem), are written like any other and compile
    against ``tilefish.hpp``. (On a GPU, ``rust_gate.py prepare`` writes the runner of every fused plan and ``cpp_gate.cpp`` runs it.)"""
    import fusion_graphs as fg
    import plan_fakes

    out = tmp_path / "gen"
    headers = []
    for name in sorted(fg.CASES):
        for twin, graph in zip(("fused", "unfused"), fg.CASES[name]):
            directory = tmp_path / f"{twin}_{name}"
            exported = plan_fakes.export(tilefish.plan(graph), directory)
            stems = {s["entry"] for b in exported.buckets() for s in exported.steps(**b) if s["kind"] == "kernel"}
            regions = {s for s in stems if s.startswith("fused_")}
            assert regions, (name, twin, stems)  # the unfused twin has a region per op
            namespace = f"{twin}_{name}"
            runner = cpp.emit_plan(exported, out / f"{namespace}_runner.hpp", namespace=namespace).read_text()
            assert f"class {''.join(w.capitalize() for w in graph.name.split('_'))} {{" in runner
            launchers = cpp.emit(pinned(Manifest.load(directory)), out / f"{namespace}_launchers.hpp", namespace=f"{namespace}_kernels").read_text()
            for stem in regions:
                assert f'static constexpr const char* STEM = "{stem}";' in launchers, stem
            headers += [f"{namespace}_runner.hpp", f"{namespace}_launchers.hpp"]
    main = out / "fused.cpp"
    main.write_text("".join(f'#include "{h}"\n' for h in headers) + "int main() { return 0; }\n")
    compile_syntax([main], [out])


@needs_cxx
@needs_cargo
@needs_capi
def test_an_embedded_manifest_loads_through_the_c_abi(tmp_path, fake_manifest):
    """The launchers of the fake manifest, with the manifest embedded, linked against ``libtilefish_capi``: ``load_embedded()`` verifies the files
    with the pin (no driver needed), and a manifest of another digest is refused by ``require_digest`` with a status."""
    target = REPO_ROOT / "target" / "capi-check"
    env = {**os.environ, "CARGO_TARGET_DIR": str(target)}
    done = subprocess.run(
        ["cargo", "build", "-p", "tilefish-capi", "--manifest-path", str(REPO_ROOT / "Cargo.toml"), "--color", "never"],
        capture_output=True,
        text=True,
        env=env,
        timeout=1800,
    )
    assert done.returncode == 0, done.stderr[-4000:]
    shared = target / "debug" / ("libtilefish_capi.dylib" if sys.platform == "darwin" else "libtilefish_capi.so")
    libdir = tmp_path / "lib"  # the library under the name a program linked against it loads (on Linux, its SONAME)
    libdir.mkdir()
    for name in (shared.name, "libtilefish_capi.so.1"):
        (libdir / name).symlink_to(shared)
    out = tmp_path / "gen"
    cpp.emit(fake_manifest, out / "launchers.hpp", embed=True, namespace="fakes")
    (out / "main.cpp").write_text(
        "#include <cstdio>\n#include <cstring>\n#include \"launchers.hpp\"\n"
        "int main(int argc, char** argv) {\n"
        "    tilefish::Manifest m = fakes::load_embedded();\n"
        "    if (std::strcmp(m.digest().c_str(), fakes::MANIFEST_DIGEST) != 0 || m.label() != \"<embedded>\") return 1;\n"
        "    try {\n"
        "        tilefish::Manifest::load_trusting_directory(argv[1]).require_digest(fakes::MANIFEST_DIGEST);\n"
        "        return 2;\n"
        "    } catch (const tilefish::Error& e) {\n"
        "        std::printf(\"%s\\n\", e.status_name());\n"
        "        return e.status() == TILEFISH_ERROR_PIN_MISMATCH ? 0 : 3;\n"
        "    }\n"
        "}\n"
    )
    other = tmp_path / "other"
    built = [fake_build(s) for s in compile_specs(scale)]
    write_manifest(built, other / "manifest.json", cubins=True)
    exe = tmp_path / "check"
    link = [CXX, "-std=c++17", "-I", str(INCLUDE), "-I", str(out), str(out / "main.cpp"), str(out / "launchers_embedded.cpp")]
    link += ["-L", str(libdir), "-ltilefish_capi", f"-Wl,-rpath,{libdir}", "-o", str(exe)]
    done = subprocess.run(link, capture_output=True, text=True, timeout=600)
    assert done.returncode == 0, done.stderr[-4000:]
    ran = subprocess.run([str(exe), str(other)], capture_output=True, text=True, timeout=120)
    assert ran.returncode == 0 and ran.stdout.strip() == "TILEFISH_ERROR_PIN_MISMATCH", (ran.returncode, ran.stdout, ran.stderr)
