def golden_plan_pin(name):
    return json.loads((GOLDEN_PLANS / "expected.json").read_text())[name]["plan_digest"]


def class_body(source, name):
    start = source.index(f"class {name} {{")
    return source[start : source.index("\n};\n", start)]


def launch_params(body):
    text = body[body.index("void launch(") :]
    return text[: text.index(") const {")]


def check_or_bless(path: pathlib.Path, source: str) -> None:
    if os.environ.get("TILEFISH_BLESS") == "1":
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source)
        return
    assert path.exists(), f"no {path}: run TILEFISH_BLESS=1 pytest tests/test_hosts_cpp.py and review it"
    assert source == path.read_text(), f"{path} is not what tilefish.hosts.cpp writes now; if the change is intended, rerun with TILEFISH_BLESS=1"


