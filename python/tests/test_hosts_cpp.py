def test_a_manifest_is_taken_only_pinned(fake_manifest, tmp_path):
    out = tmp_path / "out.hpp"
    directory, digest = fake_manifest.directory, fake_manifest.digest
    with pytest.raises(TilefishManifestError, match="without a trust anchor.*C\\+\\+ source"):
        cpp.emit(directory, out)
    with pytest.raises(TilefishManifestError, match="but the pin is " + "0" * 64):
        cpp.emit(directory, out, pin="0" * 64)
    loose = Manifest.load(directory)
    with pytest.raises(TilefishManifestError, match="is not pinned"):
        cpp.render(loose)
    assert not out.exists()
    assert cpp.emit(directory, out, pin=digest).read_text() == cpp.render(fake_manifest)
    with pytest.raises(TilefishManifestError, match="takes a manifest directory"):
        cpp.render(object())


def test_a_field_that_is_not_what_it_must_be_is_refused_and_writes_nothing(fake_manifest, tmp_path):
    from test_rust_host import FIELDS, edited, edited_in_memory

    out = tmp_path / "launchers.hpp"
    for name, change in sorted(FIELDS.items()):
        try:
            manifests = [edited(fake_manifest, tmp_path / name.replace(" ", "_"), change)]
        except TilefishManifestError:
            manifests = []
        manifests.append(edited_in_memory(fake_manifest, tmp_path / (name.replace(" ", "_") + "-mem"), change))
        for manifest in manifests:
            for embed in (False, True):
                with pytest.raises(TilefishManifestError, match="cannot write C\\+\\+ launchers for|C\\+\\+ source"):
                    cpp.emit(manifest, out, pin=manifest.digest, embed=embed)
        assert not out.exists() and not (tmp_path / "launchers_embedded.cpp").exists(), name


